#!/usr/bin/env python3
"""Generate body/test/trick_library.h from the mind's trick library.

The host test body/test/test_keyframe.cpp replays every first-version trick
(mind/kilo/tricks/library/*.json) through the body's real upload and player
code. This script encodes each trick exactly as the mind uploads it
(kilo.tricks.model: the TRICK_BEGIN payload and the 14 B frames) and also
writes the JSON's own timing (dur, hold, loop) so the test checks the
player's timing against the JSON and not against the encoder.

    python3 body/tools/gen_trick_library.py           write the header
    python3 body/tools/gen_trick_library.py --check   exit 1 if it is stale
                                                      (mind/tests runs this)
"""

from __future__ import annotations

import json
import sys
from pathlib import Path

REPO = Path(__file__).resolve().parents[2]
OUT = REPO / "body" / "test" / "trick_library.h"
sys.path.insert(0, str(REPO / "mind"))

from kilo.tricks import library  # noqa: E402
from kilo.tricks.model import Trick  # noqa: E402

TRICK_ID_BASE = 0x40


def c_bytes(data: bytes) -> str:
    return ", ".join(f"0x{b:02X}" for b in data)


def render() -> str:
    out = [
        "// Generated by body/tools/gen_trick_library.py from mind/kilo/tricks/library/*.json.",
        "// Do not edit; re-run the script (mind/tests/test_trick_player.py checks it is current).",
        "#ifndef KILO_TEST_TRICK_LIBRARY_H",
        "#define KILO_TEST_TRICK_LIBRARY_H",
        "#include <stdint.h>",
        "",
        "struct LibTrick {",
        "  const char* name;",
        "  uint8_t begin[11];       // TRICK_BEGIN payload",
        "  uint8_t n;               // frames",
        "  const uint8_t* frames;   // n x 14 B, as uploaded",
        "  uint16_t crc;            // TRICK_COMMIT crc16",
        "  const uint8_t* dur;      // per frame, from the JSON",
        "  const uint8_t* hold;",
        "  uint8_t loop_start, loop_end, repeats;",
        "  uint16_t total_ticks;    // Trick.duration_ticks (one play at 1x)",
        "};",
        "",
    ]
    rows = []
    for i, name in enumerate(library.names()):
        path = library.path_for(name)
        raw = json.loads(path.read_text())
        t = Trick.from_json(path.read_text())
        tid = TRICK_ID_BASE + i
        begin = t.begin(tid).pack()
        assert len(begin) == 11, len(begin)
        frames = t.encode_frames()
        durs = bytes(f["dur"] for f in raw["frames"])
        holds = bytes(f.get("hold", 0) for f in raw["frames"])
        ident = name.upper()
        out.append(f"static const uint8_t {ident}_FRAMES[] = {{{c_bytes(frames)}}};")
        out.append(f"static const uint8_t {ident}_DUR[] = {{{c_bytes(durs)}}};")
        out.append(f"static const uint8_t {ident}_HOLD[] = {{{c_bytes(holds)}}};")
        loop = raw.get("loop", {})
        rows.append(f'  {{"{name}", {{{c_bytes(begin)}}}, {len(t.frames)}, {ident}_FRAMES, 0x{t.crc16():04X}, '
                    f'{ident}_DUR, {ident}_HOLD, {loop.get("start", 0)}, {loop.get("end", 0)}, '
                    f'{loop.get("repeats", 0)}, {t.duration_ticks}}},')
    out.append("")
    out.append("static const LibTrick LIB_TRICKS[] = {")
    out.extend(rows)
    out.append("};")
    out.append(f"#define LIB_TRICK_COUNT {len(rows)}")
    out.append("")
    out.append("#endif")
    return "\n".join(out) + "\n"


def main(argv: list[str]) -> int:
    text = render()
    if "--check" in argv:
        if not OUT.exists() or OUT.read_text() != text:
            print(f"{OUT} is stale: run python3 body/tools/gen_trick_library.py", file=sys.stderr)
            return 1
        return 0
    OUT.write_text(text)
    print(f"wrote {OUT.relative_to(REPO)}")
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))

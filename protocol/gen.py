def _load_file_module(name: str, path: Path) -> types.ModuleType:
    import importlib.util
    spec = importlib.util.spec_from_file_location(name, path)
    mod = importlib.util.module_from_spec(spec)
    sys.modules[name] = mod  # dataclasses look the module up while building classes
    try:
        spec.loader.exec_module(mod)
    finally:
        del sys.modules[name]
    return mod


def gen_vectors(py_src: str) -> tuple[str, str]:
    """Build vectors with the freshly generated bindings and the Python codec.
    Uses private module objects so callers' imports are not disturbed."""
    P = types.ModuleType("kilo_protocol")
    P.__file__ = str(OUT_PY)
    saved = sys.modules.get("kilo_protocol")
    sys.modules["kilo_protocol"] = P
    try:
        exec(compile(py_src, str(OUT_PY), "exec"), P.__dict__)
        codec = _load_file_module("_kilo_gen_codec", HERE / "py" / "kilo_link_codec.py")
        cases = _load_file_module("_kilo_gen_cases", HERE / "vector_cases.py")
    finally:
        if saved is None:
            del sys.modules["kilo_protocol"]
        else:
            sys.modules["kilo_protocol"] = saved
    frames, cobs = cases.build(P, codec)
    return (json.dumps(frames, indent=1) + "\n", json.dumps(cobs, indent=1) + "\n")



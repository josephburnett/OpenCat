#!/usr/bin/env python3
"""Generate the Kilo protocol bindings from protocol/spec.toml.

Outputs (all committed):
  protocol/gen/kilo_protocol.h    C99/C++ header: ids, enums, packed structs, constants
  protocol/gen/kilo_protocol.py   Python dataclasses with pack/unpack, enums, constants
  protocol/vectors/frames.json    framed test vectors (cases in vector_cases.py)
  protocol/vectors/cobs.json      COBS-only vectors

Usage:
  python3 protocol/gen.py           regenerate in place
  python3 protocol/gen.py --check   exit 1 if any committed output is stale

Standard library only (Python 3.11+ for tomllib). Output is deterministic.
"""
from __future__ import annotations

import argparse
import json
import re
import sys
import tomllib
import types
from pathlib import Path

HERE = Path(__file__).resolve().parent
SPEC = HERE / "spec.toml"
OUT_H = HERE / "gen" / "kilo_protocol.h"
OUT_PY = HERE / "gen" / "kilo_protocol.py"
OUT_FRAMES = HERE / "vectors" / "frames.json"
OUT_COBS = HERE / "vectors" / "cobs.json"

SCALARS = {
    # name: (size, signed, struct char, C type)
    "u8": (1, False, "B", "uint8_t"),
    "i8": (1, True, "b", "int8_t"),
    "u16": (2, False, "H", "uint16_t"),
    "i16": (2, True, "h", "int16_t"),
    "u32": (4, False, "I", "uint32_t"),
}
KINDS = ("goal", "command", "stream", "event")
C_KEYWORDS = {"default", "int", "char", "short", "long", "signed", "unsigned",
              "struct", "union", "enum", "if", "else", "for", "while", "do",
              "switch", "case", "break", "continue", "return", "goto", "static",
              "const", "volatile", "register", "auto", "extern", "typedef",
              "void", "float", "double", "sizeof", "inline", "restrict",
              "class", "new", "delete", "this", "template", "bool", "true", "false"}
HEADER_NOTE = "GENERATED by protocol/gen.py from protocol/spec.toml. Do not edit."


class SpecError(Exception):
    pass


# ---------------------------------------------------------------------------
# Spec model

def camel(name: str) -> str:
    return "".join(p.capitalize() for p in name.lower().split("_"))


def c_ident(name: str) -> str:
    return name + "_" if name in C_KEYWORDS else name


def load_spec(path: Path = SPEC) -> dict:
    with open(path, "rb") as f:
        spec = tomllib.load(f)
    validate(spec)
    return spec


def struct_size(spec: dict, sname: str) -> int:
    return sum(field_size(spec, f) for f in spec["structs"][sname]["fields"])


def field_size(spec: dict, f: dict) -> int:
    t = f["type"]
    if t in SCALARS:
        return SCALARS[t][0] * f.get("count", 1)
    if t in spec.get("structs", {}):
        return struct_size(spec, t) * f.get("count", 1)
    raise SpecError(f"unknown type {t!r} in field {f['name']!r}")


def is_tail(f: dict) -> bool:
    return f["type"] == "bytes" or "count_field" in f


def layout(spec: dict, m: dict) -> dict:
    """Fixed prefix length, tail description, min/max payload lengths."""
    fixed = 0
    tail = None
    offsets = {}
    for i, f in enumerate(m["fields"]):
        if is_tail(f):
            if i != len(m["fields"]) - 1:
                raise SpecError(f"{m['name']}: variable field {f['name']} must be last")
            elem = 1 if f["type"] == "bytes" else struct_size(spec, f["type"])
            tail = {"field": f, "elem": elem, "min": f["min"], "max": f["max"]}
            if "count_field" in f:
                names = [g["name"] for g in m["fields"][:i]]
                if f["count_field"] not in names:
                    raise SpecError(f"{m['name']}: count_field {f['count_field']} not found")
                cf = m["fields"][names.index(f["count_field"])]
                if cf["type"] != "u8":
                    raise SpecError(f"{m['name']}: count field must be u8")
                tail["count_offset"] = offsets[cf["name"]]
            offsets[f["name"]] = fixed
        else:
            offsets[f["name"]] = fixed
            fixed += field_size(spec, f)
    lo = fixed + (tail["elem"] * tail["min"] if tail else 0)
    hi = fixed + (tail["elem"] * tail["max"] if tail else 0)
    return {"fixed": fixed, "tail": tail, "min": lo, "max": hi, "offsets": offsets}


def validate(spec: dict) -> None:
    link = spec["link"]
    ids, names = set(), set()
    for m in spec["messages"]:
        n, i = m["name"], m["id"]
        if i in ids or n in names:
            raise SpecError(f"duplicate message {n} / {i:#x}")
        ids.add(i)
        names.add(n)
        if m["kind"] not in KINDS:
            raise SpecError(f"{n}: bad kind {m['kind']}")
        if m["dir"] == "pi_to_body":
            if not 0x01 <= i <= 0x7F or m["kind"] not in ("goal", "command", "stream"):
                raise SpecError(f"{n}: Pi->body must be 0x01..0x7F and goal/command/stream (a stream is not acked)")
        elif m["dir"] == "body_to_pi":
            if not 0x80 <= i <= 0xFF or m["kind"] not in ("stream", "event"):
                raise SpecError(f"{n}: body->Pi must be 0x80..0xFF and stream/event")
        else:
            raise SpecError(f"{n}: bad dir {m['dir']}")
        if m.get("epoch"):
            f0 = m["fields"][0] if m["fields"] else None
            if not f0 or f0["name"] != "epoch" or f0["type"] != "u8":
                raise SpecError(f"{n}: epoch messages must start with epoch u8")
        lay = layout(spec, m)
        if lay["max"] > link["max_payload"]:
            raise SpecError(f"{n}: max payload {lay['max']} > {link['max_payload']}")
        for f in m["fields"]:
            if "enum" in f and f["enum"] not in spec["enums"]:
                raise SpecError(f"{n}.{f['name']}: unknown enum {f['enum']}")
            if "flags" in f and f["flags"] not in spec["flags"]:
                raise SpecError(f"{n}.{f['name']}: unknown flags {f['flags']}")
            if f["type"] not in SCALARS and not is_tail(f):
                raise SpecError(f"{n}.{f['name']}: struct fields only allowed as variable tails")
        if "reply_to" in m and m["reply_to"] not in names | {x["name"] for x in spec["messages"]}:
            raise SpecError(f"{n}: unknown reply_to {m['reply_to']}")
    for s in spec.get("structs", {}).values():
        for f in s["fields"]:
            if f["type"] not in SCALARS:
                raise SpecError("struct fields must be scalars or scalar arrays")
    if link["max_decoded"] != link["header_bytes"] + link["max_payload"] + link["crc_bytes"]:
        raise SpecError("link: max_decoded inconsistent")
    if link["max_wire"] != link["max_decoded"] + 2:
        raise SpecError("link: max_wire inconsistent")
    if link["frame_overhead"] != link["header_bytes"] + link["crc_bytes"] + 2:
        raise SpecError("link: frame_overhead inconsistent")
    replied = {m["reply_to"] for m in spec["messages"] if "reply_to" in m}
    for m in spec["messages"]:
        if m.get("query"):
            if m["kind"] != "command" or m["dir"] != "pi_to_body":
                raise SpecError(f"{m['name']}: only Pi->body commands can be queries")
            if m["name"] not in replied:
                raise SpecError(f"{m['name']}: a query needs a reply message (reply_to)")
        elif m["name"] in replied:
            raise SpecError(f"{m['name']}: has a reply message but is not a query")
    pids, pnames = set(), set()
    for p in spec.get("params", []):
        if p["id"] in pids or p["name"] in pnames:
            raise SpecError(f"duplicate param {p['name']} / {p['id']}")
        pids.add(p["id"])
        pnames.add(p["name"])
        if not 0 <= p["id"] < link["param_slots"]:
            raise SpecError(f"param {p['name']}: id must be < link.param_slots")
        if not -32768 <= p["min"] <= p["default"] <= p["max"] <= 32767:
            raise SpecError(f"param {p['name']}: need i16 min <= default <= max")
    if sorted(pids) != list(range(len(pids))):
        raise SpecError("param ids must be dense from 0")
    validate_shared(spec)


def field_range(spec: dict, msg: str, name: str) -> tuple[int, int]:
    m = next(m for m in spec["messages"] if m["name"] == msg)
    f = next(f for f in m["fields"] if f["name"] == name)
    return tuple(f["range"])


def validate_shared(spec: dict) -> None:
    """The shared defaults and limits ([gait], link.feet_*, [[joints]], [balance],
    [head]) against each other and the wire ranges."""
    link = spec["link"]
    g = spec["gait"]
    if set(g) != {"stance_h_256"}:
        raise SpecError("gait: unexpected or missing keys")
    if not 1 <= g["stance_h_256"] <= 255:
        raise SpecError("gait.stance_h_256: 1..255")
    for k in ("feet_depth", "feet_lookahead_ticks", "feet_hold_ticks"):
        if not 1 <= link[k] <= 32:
            raise SpecError(f"link.{k}: 1..32")
    if link["feet_lookahead_ticks"] >= link["feet_depth"]:
        raise SpecError("link.feet_lookahead_ticks must be below feet_depth")
    joints = spec["joints"]
    if [j["id"] for j in joints] != list(range(link["channel_count"])):
        raise SpecError("joints: ids 0..channel_count-1, in order")
    if sum(bool(j["driven"]) for j in joints) != link["joint_count"]:
        raise SpecError("joints: driven count != link.joint_count")
    if len({j["name"] for j in joints}) != len(joints):
        raise SpecError("joints: duplicate name")
    for j in joints:
        if not -128 <= j["lo"] <= j["hi"] <= 127:
            raise SpecError(f"joint {j['name']}: need int8 lo <= hi")
    b = spec["balance"]
    if set(b) != {"kp_q8", "kd_ms", "deadband_deg", "max_corr_deg", "limit_deg"}:
        raise SpecError("balance: unexpected or missing keys")
    for k in ("deadband_deg", "max_corr_deg"):
        if field_range(spec, "SET_BALANCE", k)[1] != b["limit_deg"]:
            raise SpecError(f"balance.limit_deg != SET_BALANCE {k} range max")
        if not 0 <= b[k] <= b["limit_deg"]:
            raise SpecError(f"balance.{k}: 0..limit_deg")
    for k in ("kp_q8", "kd_ms"):
        if not 0 <= b[k] <= 255:
            raise SpecError(f"balance.{k}: u8")
    # SET_BALANCE's field notes quote the defaults ("default 128 = 0.5").
    m = next(m for m in spec["messages"] if m["name"] == "SET_BALANCE")
    for f in m["fields"]:
        d = re.match(r"default (\d+)", f.get("note", ""))
        if d and int(d.group(1)) != b[f["name"]]:
            raise SpecError(f"SET_BALANCE.{f['name']}: note says default {d.group(1)}, balance.{f['name']} = {b[f['name']]}")
    h = spec["head"]
    if set(h) != {"speed_dps", "max_deg", "not_held"}:
        raise SpecError("head: unexpected or missing keys")
    if h["not_held"] != -32768 or not 0 < h["max_deg"] * 16 <= 32767 or not 0 <= h["speed_dps"] <= 0xFFFF:
        raise SpecError("head: not_held -32768, max_deg * 16 within i16, speed_dps u16")


# ---------------------------------------------------------------------------
# C header

def c_scalar_decl(f: dict) -> str:
    ctype = SCALARS[f["type"]][3]
    arr = f"[{f['count']}]" if "count" in f else ""
    return f"{ctype} {c_ident(f['name'])}{arr};"


def c_comment(f: dict) -> str:
    bits = []
    if "unit" in f:
        u = f["unit"]
        if "scale" in f:
            u = f"{u} x {f['scale']:g}"
        bits.append(u)
    if "range" in f:
        bits.append(f"range {f['range'][0]}..{f['range'][1]}")
    if "enum" in f:
        bits.append(f"enum {f['enum']}")
    if "flags" in f:
        bits.append(f"flags {f['flags']}")
    if "note" in f:
        bits.append(f["note"])
    return f" /* {'; '.join(bits)} */" if bits else ""


def gen_c(spec: dict) -> str:
    L = []
    w = L.append
    meta, link = spec["meta"], spec["link"]
    w(f"/* {HEADER_NOTE}")
    w(" *")
    w(" * Kilo body <-> mind protocol. C99 and C++ compatible; no Arduino, no")
    w(" * malloc, no floats. Payload structs are packed and little-endian, so on a")
    w(" * little-endian target a payload can be memcpy'd to/from its struct.")
    w(" */")
    w("#ifndef KILO_PROTOCOL_H")
    w("#define KILO_PROTOCOL_H")
    w("")
    w("#include <stddef.h>")
    w("#include <stdint.h>")
    w("")
    w("#if defined(__BYTE_ORDER__) && defined(__ORDER_LITTLE_ENDIAN__) && __BYTE_ORDER__ != __ORDER_LITTLE_ENDIAN__")
    w("#error \"kilo_protocol.h payload structs assume a little-endian target\"")
    w("#endif")
    w("")
    w("#if defined(__cplusplus) && __cplusplus >= 201103L")
    w("#define KILO_STATIC_ASSERT(cond, tag) static_assert(cond, #tag)")
    w("#elif defined(__STDC_VERSION__) && __STDC_VERSION__ >= 201112L")
    w("#define KILO_STATIC_ASSERT(cond, tag) _Static_assert(cond, #tag)")
    w("#else")
    w("#define KILO_STATIC_ASSERT(cond, tag) typedef char kilo_static_assert_##tag[(cond) ? 1 : -1]")
    w("#endif")
    w("")
    w("#define KILO_PACKED __attribute__((packed))")
    w("")
    w("#ifdef __cplusplus")
    w('extern "C" {')
    w("#endif")
    w("")
    w("/* ---- Versions and link constants ---- */")
    w(f"#define KILO_PROTO_MAJOR {meta['proto_major']}u")
    w(f"#define KILO_PROTO_MINOR {meta['proto_minor']}u")
    for k, v in link.items():
        suffix = "UL" if v > 0xFFFF else "u"
        val = f"0x{v:04X}{suffix}" if k in ("crc_init", "crc_poly", "crc_check", "reboot_magic", "pca_full_off_bit") else f"{v}{suffix}"
        w(f"#define KILO_{k.upper()} {val}")
    w("")
    w("/* ---- Message ids ---- */")
    w("enum kilo_msg_id {")
    for m in spec["messages"]:
        w(f"    KILO_MSG_{m['name']} = 0x{m['id']:02X},")
    w("};")
    w("")
    w("/* ---- Message kinds (ack class) ---- */")
    w("enum kilo_kind {")
    for i, k in enumerate(KINDS):
        w(f"    KILO_KIND_{k.upper()} = {i},")
    w("    KILO_KIND_UNKNOWN = 255")
    w("};")
    w("")
    w("/* ---- Enums ---- */")
    for ename, vals in spec["enums"].items():
        w(f"enum kilo_{ename} {{")
        for vn, vv in vals.items():
            w(f"    KILO_{ename.upper()}_{vn} = {vv},")
        w("};")
        w("")
    w("/* ---- Bit flags (masks) ---- */")
    for fname, bits in spec["flags"].items():
        for bn, bv in bits.items():
            w(f"#define KILO_{fname.upper()}_{bn} (1u << {bv})")
        w("")
    w("/* ---- Shared element structs ---- */")
    for sname, s in spec.get("structs", {}).items():
        w(f"typedef struct KILO_PACKED kilo_{sname}_s {{")
        for f in s["fields"]:
            w(f"    {c_scalar_decl(f)}{c_comment(f)}")
        w(f"}} kilo_{sname}_t;")
        size = struct_size(spec, sname)
        w(f"#define KILO_{sname.upper()}_SIZE {size}u")
        w(f"KILO_STATIC_ASSERT(sizeof(kilo_{sname}_t) == {size}, kilo_sa_{sname}_size);")
        off = 0
        for f in s["fields"]:
            w(f"KILO_STATIC_ASSERT(offsetof(kilo_{sname}_t, {c_ident(f['name'])}) == {off}, kilo_sa_{sname}_{f['name']});")
            off += field_size(spec, f)
        w("")
    w("/* ---- Payloads ---- */")
    for m in spec["messages"]:
        lay = layout(spec, m)
        lname = m["name"].lower()
        w(f"/* 0x{m['id']:02X} {m['name']}: {m['kind']}{', epoch' if m.get('epoch') else ''}"
          f"{', reply to ' + m['reply_to'] if 'reply_to' in m else ''}. {m['doc']} */")
        if lay["tail"]:
            t = lay["tail"]
            w(f"#define KILO_{m['name']}_MIN_LEN {lay['min']}u")
            w(f"#define KILO_{m['name']}_MAX_LEN {lay['max']}u")
            w(f"#define KILO_{m['name']}_LEN_FOR(n) ({lay['fixed']}u + {t['elem']}u * (uint8_t)(n))")
        else:
            w(f"#define KILO_{m['name']}_LEN {lay['fixed']}u")
        if not m["fields"]:
            w("")
            continue
        w(f"typedef struct KILO_PACKED kilo_{lname}_s {{")
        for f in m["fields"]:
            if f["type"] == "bytes":
                w(f"    uint8_t {c_ident(f['name'])}[{f['max']}];{c_comment(f)} /* {f['min']}..{f['max']} B, length implied */")
            elif "count_field" in f:
                w(f"    kilo_{f['type']}_t {c_ident(f['name'])}[{f['max']}]; /* {f['count_field']} = {f['min']}..{f['max']} */")
            else:
                w(f"    {c_scalar_decl(f)}{c_comment(f)}")
        w(f"}} kilo_{lname}_t;")
        w(f"KILO_STATIC_ASSERT(sizeof(kilo_{lname}_t) == {lay['max']}, kilo_sa_{lname}_size);")
        for f in m["fields"]:
            w(f"KILO_STATIC_ASSERT(offsetof(kilo_{lname}_t, {c_ident(f['name'])}) == {lay['offsets'][f['name']]}, kilo_sa_{lname}_{f['name']});")
        w("")
    # helpers
    w("/* ---- Per-type helpers ---- */")
    w("enum kilo_len_status { KILO_LEN_OK = 0, KILO_LEN_BAD = 1, KILO_LEN_UNKNOWN_TYPE = 2 };")
    w("")
    msgs = spec["messages"]
    max_id = max(m["id"] for m in msgs)
    var_msgs = [m for m in msgs if layout(spec, m)["tail"]]
    w("/* Lookup tables live in flash on the AVR (avr-libc's pgmspace, not Arduino)")
    w("   and are plain const data elsewhere. */")
    w("#if defined(__AVR__)")
    w("#include <avr/pgmspace.h>")
    w("#define KILO_TABLE_ATTR PROGMEM")
    w("#define KILO_TABLE_BYTE(p) pgm_read_byte(p)")
    w("#else")
    w("#define KILO_TABLE_ATTR")
    w("#define KILO_TABLE_BYTE(p) (*(p))")
    w("#endif")
    w(f"#define KILO_MAX_MSG_ID 0x{max_id:02X}u")
    w("")
    w("/* Check a payload's length against its type's rule. Variable-length types")
    w("   also require their count field to match the length. Table entries: the")
    w("   fixed length, 0x80 + i for the i-th variable-length type, 0xFF unknown. */")
    w("static inline uint8_t kilo_payload_len_check(uint8_t type, const uint8_t *payload, uint8_t len)")
    w("{")
    by_id = {m["id"]: m for m in msgs}
    entries = []
    for i in range(max_id + 1):
        m = by_id.get(i)
        if m is None:
            entries.append("0xFF")
        elif m in var_msgs:
            entries.append(f"0x{0x80 + var_msgs.index(m):02X}")
        else:
            entries.append(str(layout(spec, m)["fixed"]))
    w("    static const uint8_t t[KILO_MAX_MSG_ID + 1u] KILO_TABLE_ATTR = {")
    for i in range(0, len(entries), 16):
        w("        " + ", ".join(entries[i:i + 16]) + f",  /* 0x{i:02X} */")
    w("    };")
    w("    uint8_t e;")
    w("    if (type > KILO_MAX_MSG_ID) return KILO_LEN_UNKNOWN_TYPE;")
    w("    e = KILO_TABLE_BYTE(&t[type]);")
    w("    if (e == 0xFFu) return KILO_LEN_UNKNOWN_TYPE;")
    w("    if (e < 0x80u) return len == e ? KILO_LEN_OK : KILO_LEN_BAD;")
    w("    switch (e) {")
    for i, m in enumerate(var_msgs):
        lay = layout(spec, m)
        t = lay["tail"]
        w(f"    case 0x{0x80 + i:02X}u: /* {m['name']} */")
        if "count_offset" in t:
            w(f"        if (len < {lay['min']}u || len > {lay['max']}u) return KILO_LEN_BAD;")
            w(f"        return len == {lay['fixed']}u + {t['elem']}u * payload[{t['count_offset']}] ? KILO_LEN_OK : KILO_LEN_BAD;")
        else:
            w(f"        return (len >= {lay['min']}u && len <= {lay['max']}u) ? KILO_LEN_OK : KILO_LEN_BAD;")
    w("    default:")
    w("        return KILO_LEN_BAD;")
    w("    }")
    w("}")
    w("")
    w("/* Kind (ack class) of a type, or KILO_KIND_UNKNOWN. */")
    w("static inline uint8_t kilo_msg_kind(uint8_t type)")
    w("{")
    w("    switch (type) {")
    for k in KINDS:
        ms = [m for m in msgs if m["kind"] == k]
        for m in ms:
            w(f"    case KILO_MSG_{m['name']}:")
        w(f"        return KILO_KIND_{k.upper()};")
    w("    default:")
    w("        return KILO_KIND_UNKNOWN;")
    w("    }")
    w("}")
    w("")

    def mask_fn(name: str, doc: str, pred) -> None:
        groups: dict[int, int] = {}
        for m in msgs:
            if pred(m):
                groups[m["id"] >> 4] = groups.get(m["id"] >> 4, 0) | (1 << (m["id"] & 15))
        names = ", ".join(m["name"] for m in msgs if pred(m))
        w(f"/* {doc} ({names}). A bit mask per high nibble: smaller than a switch on AVR. */")
        w(f"static inline uint8_t {name}(uint8_t type)")
        w("{")
        w("    uint16_t m;")
        w("    switch (type >> 4) {")
        for g in sorted(groups):
            w(f"    case {g}u: m = 0x{groups[g]:04X}u; break;")
        w("    default: return 0u;")
        w("    }")
        w("    return (uint8_t)((m >> (type & 15u)) & 1u);")
        w("}")
        w("")

    mask_fn("kilo_msg_is_goal", "Nonzero for a goal: never acked; rejections are EVENT GOAL_REFUSED",
            lambda m: m["kind"] == "goal")
    mask_fn("kilo_msg_is_query", "Nonzero for a query: a command answered by its data reply only (ACK only on failure), never de-duplicated",
            lambda m: bool(m.get("query")))
    mask_fn("kilo_msg_has_epoch", "Nonzero if the type's payload begins with the goal epoch byte",
            lambda m: bool(m.get("epoch")))
    params = sorted(spec.get("params", []), key=lambda p: p["id"])
    w("/* ---- Live parameters (PARAM_GET / PARAM_SET) ---- */")
    w("enum kilo_param_id {")
    for p in params:
        w(f"    KILO_PARAM_{p['name']} = {p['id']}, /* {p['unit']}: {p['doc']} */")
    w("};")
    w(f"#define KILO_PARAM_COUNT {len(params)}u")
    for p in params:
        w(f"#define KILO_PARAM_{p['name']}_DEFAULT {p['default']}")
        w(f"#define KILO_PARAM_{p['name']}_MIN {p['min']}")
        w(f"#define KILO_PARAM_{p['name']}_MAX {p['max']}")
    w("/* Initializer for an int16_t [KILO_PARAM_COUNT][3] table of {min, max, default}, in id order. */")
    w("#define KILO_PARAM_TABLE_INIT { \\")
    for p in params:
        w(f"    {{{p['min']}, {p['max']}, {p['default']}}}, /* {p['name']} */ \\")
    w("}")
    w("/* Initializer for an int16_t [KILO_PARAM_COUNT] array of defaults, in id order. */")
    w("#define KILO_PARAM_DEFAULTS_INIT { " + ", ".join(str(p["default"]) for p in params) + " }")
    w("")
    gen_c_shared(spec, w)
    # field table for tests / tools (opt-in, costs flash)
    w("#ifdef KILO_PROTOCOL_FIELD_TABLE")
    w("/* Scalar field layout, for host tests and tools. Not for the AVR build. */")
    w("typedef struct kilo_field_info {")
    w("    uint8_t msg;")
    w("    const char *name;")
    w("    uint8_t offset;")
    w("    uint8_t size;      /* bytes per element */")
    w("    uint8_t is_signed;")
    w("    uint8_t count;     /* elements (1 for scalars) */")
    w("} kilo_field_info_t;")
    w("static const kilo_field_info_t kilo_field_table[] = {")
    for m in spec["messages"]:
        lay = layout(spec, m)
        for f in m["fields"]:
            if f["type"] not in SCALARS:
                continue
            size, signed, _, _ = SCALARS[f["type"]]
            w(f"    {{KILO_MSG_{m['name']}, \"{f['name']}\", {lay['offsets'][f['name']]}, {size}, {int(signed)}, {f.get('count', 1)}}},")
    w("};")
    w("#define KILO_FIELD_TABLE_LEN (sizeof(kilo_field_table) / sizeof(kilo_field_table[0]))")
    w("")
    w("typedef struct kilo_msg_info {")
    w("    uint8_t id;")
    w("    const char *name;")
    w("    uint8_t kind;          /* enum kilo_kind */")
    w("    uint8_t fixed_len;     /* bytes before the variable tail */")
    w("    uint8_t elem_size;     /* tail element size (0 = fixed-length message) */")
    w("    uint8_t tail_min;      /* tail elements, min..max */")
    w("    uint8_t tail_max;")
    w("    uint8_t count_offset;  /* offset of the u8 count field, 0xFF = implied by length */")
    w("} kilo_msg_info_t;")
    w("static const kilo_msg_info_t kilo_msg_table[] = {")
    for m in spec["messages"]:
        lay = layout(spec, m)
        t = lay["tail"]
        if t:
            w(f"    {{KILO_MSG_{m['name']}, \"{m['name']}\", KILO_KIND_{m['kind'].upper()}, {lay['fixed']}, {t['elem']}, {t['min']}, {t['max']}, {t.get('count_offset', 0xFF)}}},")
        else:
            w(f"    {{KILO_MSG_{m['name']}, \"{m['name']}\", KILO_KIND_{m['kind'].upper()}, {lay['fixed']}, 0, 0, 0, 255}},")
    w("};")
    w("#define KILO_MSG_TABLE_LEN (sizeof(kilo_msg_table) / sizeof(kilo_msg_table[0]))")
    w("#endif /* KILO_PROTOCOL_FIELD_TABLE */")
    w("")
    w("#ifdef __cplusplus")
    w("}")
    w("#endif")
    w("")
    w("#endif /* KILO_PROTOCOL_H */")
    return "\n".join(L) + "\n"


def gen_c_shared(spec: dict, w) -> None:
    """Shared defaults and limits: #defines and table initializers only (no
    objects), so a unit pays nothing for what it does not use and a table
    lives where its user declares it (PROGMEM on the AVR: flash, never RAM)."""
    def num(v: int) -> str:
        return f"({v})" if v < 0 else str(v)

    g = spec["gait"]
    w("/* ---- Shared defaults and limits (spec [gait], [[joints]], [balance], [head]) ---- */")
    w(f"#define KILO_GAIT_STANCE_H_256 {g['stance_h_256']} /* STANCE's body height, /256 of L1 + L2 */")
    w("/* Joint limits, whole degrees, by legacy joint id. */")
    for j in spec["joints"]:
        n = j["name"].upper()
        w(f"#define KILO_JOINT_{n}_ID {j['id']}")
        w(f"#define KILO_JOINT_{n}_LO {num(j['lo'])}")
        w(f"#define KILO_JOINT_{n}_HI {num(j['hi'])}")
    w("/* Initializer for an int8_t [KILO_CHANNEL_COUNT][2] table of {lo, hi}, in id order. */")
    w("#define KILO_JOINT_LIMITS_INIT { \\")
    for j in spec["joints"]:
        w(f"    {{{j['lo']}, {j['hi']}}}, /* {j['id']} {j['name']} */ \\")
    w("}")
    b = spec["balance"]
    w("/* SET_BALANCE state at boot; dead band and clamp above LIMIT_DEG are BAD_ARG. */")
    for k in ("kp_q8", "kd_ms", "deadband_deg", "max_corr_deg", "limit_deg"):
        w(f"#define KILO_BALANCE_{k.upper()} {b[k]}")
    h = spec["head"]
    w("/* SET_HEAD: the mind's default slew (deg/s) and target limit (deg); the i16 that leaves a joint to its owner. */")
    w(f"#define KILO_HEAD_SPEED_DPS {h['speed_dps']}")
    w(f"#define KILO_HEAD_MAX_DEG {h['max_deg']}")
    w(f"#define KILO_HEAD_NOT_HELD ((int16_t)({h['not_held'] + 1} - 1))")
    w("")



def py_fmt(spec: dict, fields: list) -> str:
    out = ""
    for f in fields:
        c = SCALARS[f["type"]][2]
        out += c * f.get("count", 1)
    return out


def py_struct_class(spec: dict, cname: str, fields: list, lines: list, size: int) -> None:
    w = lines.append
    fmt = py_fmt(spec, fields)
    w("@dataclass")
    w(f"class {cname}:")
    w(f"    SIZE: ClassVar[int] = {size}")
    w(f"    _FMT: ClassVar[struct.Struct] = struct.Struct('<{fmt}')")
    for f in fields:
        w(f"    {py_field_decl(f)}")
    py_pack_methods(fields, lines, tail=None)
    w("")
    w("")


def py_field_decl(f: dict) -> str:
    c = c_comment(f).strip()
    comment = ("  # " + c[3:-3].strip()) if c else ""
    if "count" in f:
        return f"{f['name']}: list[int] = field(default_factory=lambda: [0] * {f['count']}){comment}"
    return f"{f['name']}: int = 0{comment}"


def py_pack_methods(fields: list, lines: list, tail: dict | None) -> None:
    """Emit _pack_fixed/_unpack_fixed for scalar (and scalar-array) fields."""
    w = lines.append
    # pack
    w("")
    w("    def _fixed_values(self) -> list:")
    w("        v: list = []")
    for f in fields:
        if is_tail(f):
            continue
        if tail and "count_field" in tail["field"] and f["name"] == tail["field"]["count_field"]:
            w(f"        v.append(len(self.{tail['field']['name']}))")
        elif "count" in f:
            w(f"        if len(self.{f['name']}) != {f['count']}:")
            w(f"            raise PayloadError('{f['name']}: expected {f['count']} elements')")
            w(f"        v.extend(self.{f['name']})")
        else:
            w(f"        v.append(self.{f['name']})")
    w("        return v")
    w("")
    w("    @classmethod")
    w("    def _from_fixed(cls, v: tuple, **extra):")
    w("        kw: dict = {}")
    i = 0
    for f in fields:
        if is_tail(f):
            continue
        n = f.get("count", 1)
        if tail and "count_field" in tail["field"] and f["name"] == tail["field"]["count_field"]:
            i += 1
            continue
        if "count" in f:
            w(f"        kw['{f['name']}'] = list(v[{i}:{i + n}])")
        else:
            w(f"        kw['{f['name']}'] = v[{i}]")
        i += n
    w("        kw.update(extra)")
    w("        return cls(**kw)")
    if tail is None:
        w("")
        w("    def pack(self) -> bytes:")
        w("        try:")
        w("            return self._FMT.pack(*self._fixed_values())")
        w("        except struct.error as e:")
        w("            raise PayloadError(f'{type(self).__name__}: {e}') from None")
        w("")
        w("    @classmethod")
        w("    def unpack(cls, data: bytes):")
        w("        if len(data) != cls._FMT.size:")
        w("            raise PayloadError(f'{cls.__name__}: length {len(data)} != {cls._FMT.size}')")
        w("        return cls._from_fixed(cls._FMT.unpack(bytes(data)))")


def gen_py(spec: dict) -> str:
    L: list[str] = []
    w = L.append
    meta, link = spec["meta"], spec["link"]
    w(f'"""{HEADER_NOTE}')
    w("")
    w("Kilo body <-> mind protocol: message ids, enums, constants and payload")
    w("dataclasses with pack()/unpack(). Field values are raw integers (see the")
    w("comments for units and scaling). Standard library only.")
    w('"""')
    w("from __future__ import annotations")
    w("")
    w("import enum")
    w("import struct")
    w("from dataclasses import dataclass, field, fields as dc_fields")
    w("from typing import Any, ClassVar")
    w("")
    w(f"PROTO_MAJOR = {meta['proto_major']}")
    w(f"PROTO_MINOR = {meta['proto_minor']}")
    for k, v in link.items():
        val = f"0x{v:04X}" if k in ("crc_init", "crc_poly", "crc_check", "reboot_magic", "pca_full_off_bit") else str(v)
        w(f"{k.upper()} = {val}")
    w("")
    w("")
    w("class PayloadError(ValueError):")
    w('    """A payload does not match its type\'s layout (wrong length, bad count, value out of type range)."""')
    w("")
    w("")
    w("class Kind(enum.Enum):")
    for k in KINDS:
        w(f"    {k.upper()} = '{k}'")
    w("")
    w("")
    w("class Dir(enum.Enum):")
    w("    PI_TO_BODY = 'pi_to_body'")
    w("    BODY_TO_PI = 'body_to_pi'")
    w("")
    w("")
    w("class MsgId(enum.IntEnum):")
    for m in spec["messages"]:
        w(f"    {m['name']} = 0x{m['id']:02X}")
    w("")
    w("")
    msg_classes = {camel(m["name"]) for m in spec["messages"]}
    for ename, vals in spec["enums"].items():
        # [enums.event] would shadow (or be shadowed by) the EVENT message class.
        cname = camel(ename) + ("Code" if camel(ename) in msg_classes else "")
        w(f"class {cname}(enum.IntEnum):")
        for vn, vv in vals.items():
            w(f"    {vn} = {vv}")
        w("")
        w("")
    for fname, bits in spec["flags"].items():
        w(f"class {camel(fname)}(enum.IntFlag):")
        for bn, bv in bits.items():
            w(f"    {bn} = 1 << {bv}")
        w("")
        w("")
    w("LEN_OK = 0")
    w("LEN_BAD = 1")
    w("LEN_UNKNOWN_TYPE = 2")
    w("")
    w("")
    for sname, s in spec.get("structs", {}).items():
        py_struct_class(spec, camel(sname), s["fields"], L, struct_size(spec, sname))
    for m in spec["messages"]:
        lay = layout(spec, m)
        tail = lay["tail"]
        cname = camel(m["name"])
        prefix_fields = [f for f in m["fields"] if not is_tail(f)]
        fmt = py_fmt(spec, prefix_fields)
        w("@dataclass")
        w(f"class {cname}:")
        w(f'    """0x{m["id"]:02X} {m["name"]} ({m["kind"]}). {m["doc"]}"""')
        w(f"    ID: ClassVar[int] = 0x{m['id']:02X}")
        w(f"    NAME: ClassVar[str] = '{m['name']}'")
        w(f"    KIND: ClassVar[Kind] = Kind.{m['kind'].upper()}")
        w(f"    DIR: ClassVar[Dir] = Dir.{m['dir'].upper()}")
        w(f"    HAS_EPOCH: ClassVar[bool] = {bool(m.get('epoch'))}")
        w(f"    IS_QUERY: ClassVar[bool] = {bool(m.get('query'))}")
        w(f"    REPLY_TO: ClassVar[int | None] = {('0x%02X' % next(x['id'] for x in spec['messages'] if x['name'] == m['reply_to'])) if 'reply_to' in m else None}")
        w(f"    MIN_LEN: ClassVar[int] = {lay['min']}")
        w(f"    MAX_LEN: ClassVar[int] = {lay['max']}")
        w(f"    _FMT: ClassVar[struct.Struct] = struct.Struct('<{fmt}')")
        for f in m["fields"]:
            if tail and "count_field" in tail["field"] and f["name"] == tail["field"]["count_field"]:
                continue  # derived from len(tail list)
            if f["type"] == "bytes":
                w(f"    {f['name']}: bytes = b''  # {f['min']}..{f['max']} B")
            elif "count_field" in f:
                w(f"    {f['name']}: list[{camel(f['type'])}] = field(default_factory=list)  # {f['min']}..{f['max']}, count in {f['count_field']}")
            else:
                w(f"    {py_field_decl(f)}")
        py_pack_methods(m["fields"], L, tail)
        if tail:
            tf = tail["field"]
            w("")
            w("    def pack(self) -> bytes:")
            if tf["type"] == "bytes":
                w(f"        tail = bytes(self.{tf['name']})")
                w(f"        n = len(tail)")
            else:
                w(f"        n = len(self.{tf['name']})")
                w(f"        tail = b''.join(e.pack() for e in self.{tf['name']})")
            w(f"        if not {tail['min']} <= n <= {tail['max']}:")
            w(f"            raise PayloadError('{tf['name']}: {tail['min']}..{tail['max']} elements, got %d' % n)")
            w("        try:")
            w("            return self._FMT.pack(*self._fixed_values()) + tail")
            w("        except struct.error as e:")
            w("            raise PayloadError(f'{type(self).__name__}: {e}') from None")
            w("")
            w("    @classmethod")
            w("    def unpack(cls, data: bytes):")
            w("        data = bytes(data)")
            w("        if payload_len_status(cls.ID, data) != LEN_OK:")
            w("            raise PayloadError(f'{cls.__name__}: bad length {len(data)}')")
            w(f"        v = cls._FMT.unpack(data[:{lay['fixed']}])")
            w(f"        rest = data[{lay['fixed']}:]")
            if tf["type"] == "bytes":
                w(f"        return cls._from_fixed(v, {tf['name']}=rest)")
            else:
                ec = camel(tf["type"])
                w(f"        items = [{ec}.unpack(rest[i:i + {tail['elem']}]) for i in range(0, len(rest), {tail['elem']})]")
                w(f"        return cls._from_fixed(v, {tf['name']}=items)")
        w("")
        w("")
    # registries and helpers
    w("MESSAGES: dict[int, type] = {")
    for m in spec["messages"]:
        w(f"    0x{m['id']:02X}: {camel(m['name'])},")
    w("}")
    w("")
    w("")
    w("# Queries (answered by their data reply only, never de-duplicated) -> reply type.")
    w("QUERY_REPLY: dict[int, int] = {")
    for m in spec["messages"]:
        if "reply_to" in m:
            q = next(x for x in spec["messages"] if x["name"] == m["reply_to"])
            w(f"    0x{q['id']:02X}: 0x{m['id']:02X},  # {q['name']} -> {m['name']}")
    w("}")
    w("")
    w("")
    w("@dataclass(frozen=True)")
    w("class ParamInfo:")
    w("    id: int")
    w("    name: str")
    w("    default: int")
    w("    min: int")
    w("    max: int")
    w("    unit: str")
    w("    doc: str")
    w("")
    w("")
    params = sorted(spec.get("params", []), key=lambda p: p["id"])
    w("class ParamId(enum.IntEnum):")
    for p in params:
        w(f"    {p['name']} = {p['id']}")
    w("")
    w("")
    w("PARAMS: dict[int, ParamInfo] = {")
    for p in params:
        w(f"    {p['id']}: ParamInfo({p['id']}, {p['name']!r}, {p['default']}, {p['min']}, {p['max']}, {p['unit']!r},")
        w(f"                         {p['doc']!r}),")
    w("}")
    w("PARAMS_BY_NAME: dict[str, ParamInfo] = {p.name: p for p in PARAMS.values()}")
    w("")
    w("")
    gen_py_shared(spec, w)
    w("def payload_len_status(msg_type: int, payload: bytes) -> int:")
    w('    """LEN_OK, LEN_BAD or LEN_UNKNOWN_TYPE, exactly as kilo_payload_len_check() in C."""')
    w("    n = len(payload)")
    for m in spec["messages"]:
        lay = layout(spec, m)
        t = lay["tail"]
        w(f"    if msg_type == 0x{m['id']:02X}:")
        if not t:
            w(f"        return LEN_OK if n == {lay['fixed']} else LEN_BAD")
        elif "count_offset" in t:
            w(f"        if not {lay['min']} <= n <= {lay['max']}:")
            w("            return LEN_BAD")
            w(f"        return LEN_OK if n == {lay['fixed']} + {t['elem']} * payload[{t['count_offset']}] else LEN_BAD")
        else:
            w(f"        return LEN_OK if {lay['min']} <= n <= {lay['max']} else LEN_BAD")
    w("    return LEN_UNKNOWN_TYPE")
    w("")
    w("")
    w("def decode_payload(msg_type: int, payload: bytes) -> Any:")
    w('    """Unpack a payload into its dataclass. Raises KeyError (unknown type) or PayloadError."""')
    w("    return MESSAGES[msg_type].unpack(payload)")
    w("")
    w("")
    w("def to_dict(obj: Any) -> Any:")
    w('    """Message/struct -> plain JSON-able dict (bytes as hex strings)."""')
    w("    if isinstance(obj, (bytes, bytearray)):")
    w("        return bytes(obj).hex()")
    w("    if isinstance(obj, list):")
    w("        return [to_dict(x) for x in obj]")
    w("    if hasattr(obj, '__dataclass_fields__'):")
    w("        return {f.name: to_dict(getattr(obj, f.name)) for f in dc_fields(obj)}")
    w("    return obj")
    w("")
    w("")
    w("def from_dict(cls: type, d: dict) -> Any:")
    w('    """Inverse of to_dict for a message or struct class."""')
    w("    kw = {}")
    w("    for f in dc_fields(cls):")
    w("        k = f.name")
    w("        if k not in d:")
    w("            continue")
    w("        v = d[k]")
    w("        t = str(f.type)")
    w("        if t == 'bytes':")
    w("            v = bytes.fromhex(v)")
    w("        elif t.startswith('list[') and t != 'list[int]':")
    w("            ec = globals()[t[5:-1]]")
    w("            v = [from_dict(ec, x) for x in v]")
    w("        kw[k] = v")
    w("    return cls(**kw)")
    return "\n".join(L) + "\n"



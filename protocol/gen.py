def render() -> dict[Path, str]:
    spec = load_spec()
    h = gen_c(spec)
    py = gen_py(spec)
    frames, cobs = gen_vectors(py)
    return {OUT_H: h, OUT_PY: py, OUT_FRAMES: frames, OUT_COBS: cobs}


def main(argv: list[str] | None = None) -> int:
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    ap.add_argument("--check", action="store_true", help="fail if outputs are stale")
    args = ap.parse_args(argv)
    outputs = render()
    stale = []
    for path, text in outputs.items():
        old = path.read_text() if path.exists() else None
        if old != text:
            stale.append(path)
            if not args.check:
                path.parent.mkdir(parents=True, exist_ok=True)
                path.write_text(text)
    rel = [str(p.relative_to(HERE.parent)) for p in stale]
    if args.check:
        if stale:
            print("stale generated files (run python3 protocol/gen.py):", *rel, sep="\n  ")
            return 1
        print("generated files are up to date")
        return 0
    print("wrote:" if rel else "no changes", *rel, sep="\n  " if rel else "")
    return 0


if __name__ == "__main__":
    sys.exit(main())
